/**
 *
 *
 * Paralelas:          ax * by - ay * bx == 0
 * Perpendiculares:    ax * bx + ay * by == 0
 *
 *
 * Ecuacion punto-pendiente:
 * y - y1 = m * (x - x1)
 *
 * Pendiente:
 * m = (y2 - y1) / (x2 - x1)
 *
 * Si trabajas con pendientes:
 * m1 == m2       -> paralelas
 * m1 * m2 == -1  -> perpendiculares
 *
 */